// Returns the painted pixels of `text` as [col, row] pairs plus the total width.
window.CC_renderText = function renderText(text) {
  const pixels = [];
  let x = 0;
  for (const raw of String(text)) {
    const glyph = window.CC_FONT[raw.toUpperCase()];
    if (!glyph) continue;
    if (x > 0) x += 1;
    glyph.forEach((line, row) => {
      [...line].forEach((mark, col) => {
        if (mark === '#') pixels.push([x + col, row]);
      });
    });
    x += glyph[0].length;
  }
  return { pixels, width: x };
};
